-- Idempotent: safe to re-run.

IF NOT EXISTS (SELECT 1 FROM sys.tables t JOIN sys.schemas s ON t.schema_id = s.schema_id WHERE s.name = 'config' AND t.name = 'phc')
BEGIN
    CREATE TABLE config.phc (
        phc_id INT IDENTITY(1,1) PRIMARY KEY,
        phc_name VARCHAR(200) NOT NULL,
        taluka_id INT NOT NULL,
        district_id INT NOT NULL,
        source_phc_id INT NULL,
        is_active BIT NOT NULL DEFAULT 1,
        CONSTRAINT fk_phc_taluka FOREIGN KEY (taluka_id) REFERENCES config.taluka(taluka_id),
        CONSTRAINT fk_phc_district FOREIGN KEY (district_id) REFERENCES config.district(district_id)
    );
    CREATE INDEX ix_phc_taluka ON config.phc(taluka_id);
END

